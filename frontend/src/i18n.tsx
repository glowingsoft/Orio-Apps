type Widen<T> = {
  readonly [K in keyof T]: T[K] extends string ? string
    : T[K] extends (...args: infer A) => string ? (...args: A) => string
    : T[K];
};
type Bundle = Widen<typeof STRINGS.en>;
type Ctx = {
  lang: Lang;
  isRTL: boolean;
  t: Bundle;
  setLang: (l: Lang) => Promise<void>;
};

const I18nCtx = createContext<Ctx | null>(null);
const KEY = "orio_lang";

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    (async () => {
      try {
        const saved = (await AsyncStorage.getItem(KEY)) as Lang | null;
        if (saved === "en" || saved === "ar") {
          setLangState(saved);
          applyRTL(saved === "ar");
        }
      } catch {}
      setReady(true);
    })();
  }, []);

  const setLang = useCallback(async (l: Lang) => {
    const changedDirection = (l === "ar") !== (lang === "ar");
    setLangState(l);
    try { await AsyncStorage.setItem(KEY, l); } catch {}
    applyRTL(l === "ar");

    // Iter-90 — When the direction flips OR the language changes, do a FULL
    // reload so RTL/LTR, I18nManager.isRTL, and every t.* string takes effect
    // immediately in every screen (including screens that cache t at mount).
    if (Platform.OS === "web") {
      try {
        // Small defer so AsyncStorage.setItem completes.
        setTimeout(() => {
          // @ts-ignore
          if (typeof window !== "undefined" && window.location) {
            // @ts-ignore
            window.location.reload();
          }
        }, 60);
      } catch {}
    } else if (changedDirection) {
      // On native, direction only applies after a reload. Prefer expo-updates
      // if available; otherwise log and let the next cold start pick it up.
      try {
        // Dynamic import so web builds don't try to bundle expo-updates.
        // eslint-disable-next-line @typescript-eslint/no-var-requires
        const Updates = require("expo-updates");
        if (Updates && typeof Updates.reloadAsync === "function") {
          setTimeout(() => { void Updates.reloadAsync(); }, 60);
        }
      } catch {}
    }
  }, [lang]);

  const value = useMemo<Ctx>(() => ({
    lang,
    isRTL: lang === "ar",
    t: STRINGS[lang],
    setLang,
  }), [lang, setLang]);

  if (!ready) return null;
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

function applyRTL(rtl: boolean) {
  try {
    // React Native's I18nManager only fully applies after reload on native.
    // We still call it so future launches respect the setting.
    if (I18nManager.isRTL !== rtl) {
      I18nManager.allowRTL(rtl);
      I18nManager.forceRTL(rtl);
    }
  } catch {}
  if (Platform.OS === "web") {
    try {
      // Best-effort: flip the root document direction on web.
      // @ts-ignore
      if (typeof document !== "undefined" && document?.documentElement) {
        // @ts-ignore
        document.documentElement.dir = rtl ? "rtl" : "ltr";
      }
    } catch {}
  }
}

export function useI18n(): Ctx {
  const c = useContext(I18nCtx);
  if (!c) throw new Error("useI18n must be inside I18nProvider");
  return c;
}
